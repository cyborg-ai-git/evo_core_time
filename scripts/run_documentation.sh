PACKAGE_NAME="evo_framework"
#PACKAGE_NAME="$(basename "$(pwd)")"
DIRECTORY_BASE=$(dirname "$(realpath "$0")")
DIRECTORY_DOC="$DIRECTORY_BASE/Documentation"
DIRECTORY_DOC_DATA="$DIRECTORY_DOC/data"
DIRECTORY_RUST="$DIRECTORY_BASE/$PACKAGE_NAME"
# ---------------------------------------------------------------------------------------------------------------------------------------
clear
# ---------------------------------------------------------------------------------------------------------------------------------------
echo "🟢 RUN crate.io publish $ $DIRECTORY_BASE"
current_time=$(date +"%Y.%-m.%-d%H%M")
# ---------------------------------------------------------------------------------------------------------------------------------------
CURRENT_DIRECTORY=$(pwd)
# ---------------------------------------------------------------------------------------------------------------------------------------
cd "$DIRECTORY_BASE" || exit
cd ..
sh ../run_git_push.sh
# ---------------------------------------------------------------------------------------------------------------------------------------
cd "$DIRECTORY_DOC_DATA" || exit
for file in ./*.puml; do
  echo "$file"
  plantuml -v -tsvg "$file"
done
# ---------------------------------------------------------------------------------------------------------------------------------------
cd "$DIRECTORY_RUST" || exit
cargo clean
cargo doc --no-deps --features doc-uml --open
cp -Rf "./target/doc" "$DIRECTORY_DOC"
# ---------------------------------------------------------------------------------------------------------------------------------------
cd "$CURRENT_DIRECTORY" || exit
# ---------------------------------------------------------------------------------------------------------------------------------------